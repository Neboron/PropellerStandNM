#!/usr/bin/env python3
"""Generate both language bindings and the message reference from messages.json."""
import argparse
import json
from pathlib import Path
import struct
import sys
import zlib

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'GUI'))
from protocol.framing import crc16

TYPES = {'u8': ('B', 'uint8_t', 'U8'), 'i8': ('b', 'int8_t', 'I8'),
         'u16': ('H', 'uint16_t', 'U16'), 'u32': ('I', 'uint32_t', 'U32'),
         'i32': ('i', 'int32_t', 'I32'), 'f32': ('f', 'float', 'F32')}

def generate():
    schema = json.loads((ROOT / 'protocol/messages.json').read_text())
    canonical = json.dumps({'version': schema['version'], 'messages': [
        {k: m[k] for k in ('id', 'name', 'direction', 'fields')} for m in schema['messages']]},
        sort_keys=True, separators=(',', ':')).encode()
    schema_hash = zlib.crc32(canonical)
    py = ['# Generated by protocol/generate.py; edit protocol/messages.json instead.',
          'from enum import IntEnum', f'VERSION = {schema["version"]}', f'SCHEMA_HASH = {schema_hash}', 'class MessageId(IntEnum):']
    cpp = ['// Generated by protocol/generate.py; do not edit.', '#ifndef STAND_MESSAGES_H', '#define STAND_MESSAGES_H',
           '#include "StandLink.h"', '#include <math.h>', 'namespace standlink {',
           f'constexpr uint16_t VERSION = {schema["version"]};', f'constexpr uint32_t SCHEMA_HASH = {schema_hash}u;',
           'enum MessageId : uint8_t {']
    definitions=[]; specs=[]
    doc=['# StandLink message reference (generated)', '', 'See [protocol.md](protocol.md) for framing, lifecycle, enums, and examples.', '',
         '| ID | Name | Direction | Payload bytes | Fields in wire order | CRC extra | Meaning |',
         '|---|---|---|---:|---|---:|---|']
    seen=set()
    for m in schema['messages']:
        assert m['id'] not in seen and 0 <= m['id'] <= 255
        seen.add(m['id'])
        fs=m['fields']; variable=fs==[{'name':'text','type':'bytes'}]
        fmt=None if variable else '<'+''.join(TYPES[f['type']][0] for f in fs)
        size=None if variable else struct.calcsize(fmt)
        assert size is None or size <= 255
        # Similar purpose to MAVLink CRC_EXTRA; our own canonical schema, no field reordering.
        signature=m['name']+' '+''.join(f["type"]+' '+f['name']+' ' for f in fs)
        crc=crc16(signature.encode()); extra=(crc & 255) ^ (crc >> 8)
        py.append(f'    {m["name"]} = {m["id"]}')
        cpp.append(f'  {m["name"]} = {m["id"]},')
        definitions.append(f'    {m["id"]}: ({m["name"]!r}, {fmt!r}, {tuple(f["name"] for f in fs)!r}, {extra}, {m["direction"]!r}),')
        specs.append(f'    case {m["name"]}: extra={extra}; return {size if size is not None else -1};')
        fs_text=', '.join(f'`{f["name"]}:{f["type"]}`' for f in fs) or '—'
        doc.append(f'| {m["id"]} / 0x{m["id"]:02X} | {m["name"]} | {m["direction"]} → peer | {size if size is not None else "0–255"} | {fs_text} | {extra} | {m["description"]} |')
    py.extend(['', '# id: (name, struct format, fields, CRC extra, sender)', 'DEFINITIONS = {', *definitions, '}'])
    cpp.extend(['};', 'inline int16_t messageSpec(uint8_t id, uint8_t& extra) {', '  switch (id) {', *specs, '    default: extra=0; return -2;', '  }', '}'])
    cpp.extend(['inline bool isCommand(uint8_t id) { return id>=32 && id<=73; }'])
    for m in schema['messages']:
        fs=m['fields']
        if any(f['type']=='bytes' for f in fs): continue
        name=''.join(word.title() for word in m['name'].split('_'))
        cpp.append(f'struct {name} {{')
        for f in fs:cpp.append(f'  {TYPES[f["type"]][1]} {f["name"]};')
        cpp.extend(['};',f'inline Packet pack(const {name}& v) {{',f'  Packet out; out.id={m["name"]};', '  uint8_t* p=out.payload;'])
        if not fs:cpp.append('  (void)v;')
        for f in fs:cpp.append(f'  put{TYPES[f["type"]][2]}(p,v.{f["name"]});')
        cpp.extend(['  out.length=uint8_t(p-out.payload); return out;', '}',f'inline bool unpack(const Packet& in, {name}& v) {{',
                    f'  if (in.id!={m["name"]} || in.length!={sum(struct.calcsize(TYPES[f["type"]][0]) for f in fs)}) return false;', '  const uint8_t* p=in.payload;'])
        if not fs:cpp.append('  (void)p; (void)v;')
        for f in fs:cpp.append(f'  v.{f["name"]}=get{TYPES[f["type"]][2]}(p);')
        floats=[f'!isfinite(v.{f["name"]})' for f in fs if f['type']=='f32']
        if floats:cpp.append('  if ('+' || '.join(floats)+') return false;')
        cpp.extend(['  return true;', '}'])
    cpp.extend(['} // namespace standlink','#endif'])
    return {'PropStandController.ino': (ROOT/'PropStandController/PropStandController.ino').read_text(), 'GUI/protocol/messages.py':'\n'.join(py)+'\n','PropStandController/StandMessages.h':'\n'.join(cpp)+'\n', 'docs/message_ids.md':'\n'.join(doc)+'\n'}

if __name__ == '__main__':
    parser=argparse.ArgumentParser(); parser.add_argument('--check',action='store_true'); args=parser.parse_args()
    bad=[]
    for filename,content in generate().items():
        path=ROOT/filename
        if args.check:
            if not path.exists() or path.read_text()!=content: bad.append(filename)
        else:
            path.parent.mkdir(parents=True,exist_ok=True); path.write_text(content)
    if bad: raise SystemExit('Stale generated files: '+', '.join(bad))
